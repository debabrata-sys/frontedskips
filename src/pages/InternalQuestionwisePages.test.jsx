import React from "react";
import { render, screen, waitFor, fireEvent } from "@testing-library/react";
import Page from "./InternalQuestionwisePages";
import ep1 from "../api/ep1";
import global1 from "./global1";
jest.mock("../api/ep1", () => ({ get: jest.fn(), post: jest.fn() }));
jest.mock("./MenuPageShell", () => ({ children }) => <div>{children}</div>);
jest.mock("./EmbeddedWizardShell", () => () => null);
jest.mock("react-router-dom", () => ({ useNavigate: () => jest.fn() }));
jest.mock("@mui/x-data-grid", () => ({ DataGrid: () => null, GridToolbar: () => null }));
jest.mock("@mui/material", () => {
  const actual = jest.requireActual("@mui/material");
  return { ...actual, Autocomplete: ({ options, value, onChange, multiple, getOptionLabel, renderInput, disabled }) => {
    const input = renderInput({});
    return <select aria-label={input.props.label} disabled={disabled} value="" onChange={event => { const option = options[Number(event.target.value)]; onChange(null, multiple ? [...(value || []), option] : option); }}><option value="">Choose</option>{options.map((option, index) => <option key={index} value={index}>{getOptionLabel ? getOptionLabel(option) : String(option)}</option>)}</select>;
  } };
});
test("saving a question retains step 1 selections and clears only question details", async () => {
  global1.colid = 42;
  const course = { _id: "c1", program: "BSc", programcode: "P1", semester: "1", regulation: "R26", course: "Physics", coursecode: "PHY1" };
  ep1.get.mockImplementation(async (url, config) => ({ data: url.endsWith("questions") ? { data: [] } : !config.params.academicyear ? { exams: [{ academicyear: "2026-27", examname: "Exam", examcode: "E1" }] } : { courses: [course], cos: [{ _id: "co1", conumber: "CO1", co: "Explain" }], assessments: [{ _id: "a1", assessmentcomponent: "Test", componenttype: "Theory", marks: 10 }] } }));
  ep1.post.mockResolvedValue({ data: { saved: 1 } });
  const view = render(<Page />);
  await waitFor(() => expect(screen.getByRole("option", { name: "2026-27" })).toBeTruthy());
  fireEvent.change(screen.getByLabelText("Academic year"), { target: { value: "1" } });
  fireEvent.change(screen.getByLabelText("Exam"), { target: { value: "1" } });
  await waitFor(() => expect(screen.getByRole("option", { name: "BSc (P1)" })).toBeTruthy());
  fireEvent.change(screen.getByLabelText("Programs / program codes"), { target: { value: "1" } });
  fireEvent.change(screen.getByLabelText("Semester"), { target: { value: "1" } });
  fireEvent.change(screen.getByLabelText("Courses / course codes"), { target: { value: "1" } });
  await waitFor(() => expect(screen.getByRole("option", { name: /Test \| Theory/ })).toBeTruthy());
  fireEvent.change(screen.getByLabelText(/Assessment component - Physics/), { target: { value: "1" } });
  fireEvent.click(screen.getByRole("button", { name: "Continue to step 2" }));
  await waitFor(() => expect(screen.getByLabelText("questionno")).toBeTruthy());
  fireEvent.change(screen.getByLabelText("questionno"), { target: { value: "1" } });
  fireEvent.change(screen.getByLabelText("question"), { target: { value: "Explain physics" } });
  fireEvent.change(screen.getByLabelText("fullmarks"), { target: { value: "10" } });
  fireEvent.change(screen.getByLabelText(/CO - Physics/), { target: { value: "1" } });
  fireEvent.click(screen.getByRole("button", { name: "Save question" }));
  await waitFor(() => expect(screen.getByLabelText("questionno").value).toBe(""));
  expect(screen.getByLabelText("Academic year").disabled).toBe(true);
  expect(screen.getByLabelText("Exam code").value).toBe("E1");
  expect(ep1.post).toHaveBeenCalledWith("/api/v2/internal-questionwise/questions/save", expect.objectContaining({ academicyear: "2026-27", examcode: "E1", targets: [expect.objectContaining({ coursecode: "PHY1", coid: "co1", assessmentid: "a1" })] }));
  view.rerender(<Page mode="entry" />);
  expect(screen.getByLabelText("Exam code").value).toBe("");
  expect(screen.getByLabelText("Academic year").disabled).toBe(false);
  view.rerender(<Page mode="aggregate" />);
  expect(screen.getByLabelText("Exam code").value).toBe("");
});
